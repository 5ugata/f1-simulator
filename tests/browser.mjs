import {fileURLToPath} from 'node:url';
import {browserOptions} from './browser-options.mjs';
import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
const origin=process.env.APEX_URL||'http://127.0.0.1:4173';
const artifacts=fileURLToPath(new URL('../artifacts/',import.meta.url));
await mkdir(artifacts,{recursive:true});
const browser=await chromium.launch(browserOptions());
try{
  const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
  page.setDefaultTimeout(90000);
  await page.addInitScript(()=>localStorage.setItem('apex-settings',JSON.stringify({quality:'performance',volume:0})));
  const errors=[];
  page.on('pageerror',e=>{errors.push(e.message);console.log('PAGE ERROR',e.message)});
  page.on('console',m=>{if(m.type()==='error'&&!m.text().includes('fonts.googleapis'))errors.push(m.text())});
  await page.goto(origin,{waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>window.__APEX__?.ready,{timeout:90000});
  assert.equal(await page.evaluate(()=>__APEX__.car.asset.uid),'967ecec37468412083c40c62b3d7234d','The requested McLaren is the active car');
  assert.equal(await page.evaluate(()=>__APEX__.car.triangles),102081,'The full source mesh is retained');
  assert.equal(await page.evaluate(()=>__APEX__.vehicle.geometry.wheelbase),await page.evaluate(()=>__APEX__.car.dimensions.wheelbase),'Physics uses the imported axle spacing');
  await page.screenshot({path:`${artifacts}lobby.png`,timeout:90000});
  console.log('Ready',await page.evaluate(()=>({phase:__APEX__.phase,render:__APEX__.rendering.renderer.info.render,carPosition:__APEX__.car.group.position.toArray()})));
  await page.getByRole('button',{name:'ENTER COCKPIT'}).click();
  await page.waitForFunction(()=>__APEX__.phase==='drive',{timeout:90000});
  assert.equal(await page.evaluate(()=>__APEX__.session.outLap),true,'The grid begins an opening out lap');
  assert.equal(await page.evaluate(()=>__APEX__.session.valid),true,'A clean out lap is not a track-limit violation');
  assert.equal(await page.locator('#lap-number').textContent(),'OUT LAP');
  await page.screenshot({path:`${artifacts}cockpit.png`,timeout:90000});
  console.log('Cockpit performance',await page.evaluate(()=>({fps:__APEX__.fps,calls:__APEX__.rendering.renderer.info.render.calls,triangles:__APEX__.rendering.renderer.info.render.triangles})));
  await page.keyboard.down('w');
  await page.waitForFunction(()=>__APEX__.state.speed>20,{timeout:90000});
  await page.keyboard.up('w');
  const speed=await page.evaluate(()=>__APEX__.state.speed);
  assert(speed>20,'Car accelerates from driver input');
  await page.keyboard.down('s');
  await page.waitForFunction(()=>__APEX__.state.speed<3,{timeout:90000});
  await page.keyboard.up('s');
  await page.keyboard.press('c');
  await page.waitForTimeout(400);
  await page.screenshot({path:`${artifacts}pod.png`,timeout:90000});
  await page.keyboard.press('c');
  await page.waitForTimeout(400);
  await page.screenshot({path:`${artifacts}chase.png`,timeout:90000});
  await page.keyboard.press('c');
  await page.waitForTimeout(400);
  assert.equal(await page.evaluate(()=>__APEX__.camera),'NOSE');
  await page.screenshot({path:`${artifacts}nose.png`,timeout:90000});
  await page.keyboard.press('c');
  await page.waitForFunction(()=>__APEX__.camera==='COCKPIT');
  await page.waitForTimeout(300);
  await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(()=>__APEX__.phase),'paused');
  const pausedState=()=>({frame:__APEX__.rendering.renderer.info.render.frame,time:__APEX__.session.lapTime});
  const paused=await page.evaluate(pausedState);
  await page.waitForTimeout(250);
  assert.deepEqual(await page.evaluate(pausedState),paused,'Pause freezes simulation and main rendering');
  await page.setViewportSize({width:1400,height:900});
  await page.waitForFunction(frame=>__APEX__.rendering.renderer.info.render.frame>frame,paused.frame);
  const resized=await page.evaluate(pausedState);
  assert.equal(resized.time,paused.time,'Resizing a paused view does not advance the simulation');
  await page.setViewportSize({width:1440,height:900});
  await page.waitForFunction(()=>!__APEX__.rendering.needsRender);
  await page.screenshot({path:`${artifacts}pause.png`,timeout:90000});
  await page.getByRole('button',{name:'TELEMETRY',exact:true}).last().click();
  await page.screenshot({path:`${artifacts}telemetry.png`,timeout:90000});
  await page.keyboard.press('Escape');
  await page.waitForFunction(()=>__APEX__.phase==='drive');
  await page.keyboard.press('r');
  assert.equal(await page.evaluate(()=>__APEX__.state.speed),0);
  assert.equal(await page.evaluate(()=>__APEX__.session.valid),false);
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'EXIT TO PADDOCK'}).click();
  assert.equal(await page.evaluate(()=>__APEX__.phase),'lobby');
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByRole('switch',{name:'Traction & stability assistance'}).click();
  assert.equal(await page.evaluate(()=>__APEX__.settings.assist),false);
  await page.getByRole('switch',{name:'Traction & stability assistance'}).click();
  await page.getByRole('button',{name:'SAVE & CONTINUE'}).click();
  await page.getByRole('button',{name:'THE CIRCUIT',exact:true}).click();
  await page.screenshot({path:`${artifacts}circuit.png`,timeout:90000});
  await page.keyboard.press('Escape');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:`${artifacts}mobile.png`,timeout:90000});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'Mobile layout stays within viewport');
  await page.setViewportSize({width:1440,height:900});
  await page.getByRole('button',{name:'WATCH A LAP'}).click();
  await page.waitForFunction(()=>__APEX__.phase==='drive'&&__APEX__.state.speed>20,null,{timeout:90000});
  assert.equal(await page.evaluate(()=>__APEX__.demo),true);
  assert.equal(await page.evaluate(()=>__APEX__.session.recordEnabled),false);
  await page.getByRole('button',{name:'TAKE CONTROL'}).click();
  assert.equal(await page.evaluate(()=>__APEX__.demo),false);
  assert.equal(await page.evaluate(()=>__APEX__.session.valid),false);
  assert.equal(await page.evaluate(()=>__APEX__.session.recordEnabled),true);
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'EXIT TO PADDOCK'}).click();
  await page.getByRole('button',{name:/CONDITIONS/}).click();
  await page.getByLabel('Environment',{exact:true}).selectOption('overcast');
  assert.equal(await page.evaluate(()=>__APEX__.rendering.weather),'overcast');
  await page.getByLabel('Environment',{exact:true}).selectOption('clear');
  await page.getByRole('button',{name:'APPLY CONDITIONS'}).click();
  await page.screenshot({path:`${artifacts}clear.png`,timeout:90000});
  await page.getByRole('button',{name:/CONDITIONS/}).click();
  await page.getByLabel('Environment',{exact:true}).selectOption('golden');
  await page.getByRole('button',{name:'APPLY CONDITIONS'}).click();
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByLabel('Graphics quality',{exact:true}).selectOption('high');
  await page.getByRole('button',{name:'SAVE & CONTINUE'}).click();
  await page.screenshot({path:`${artifacts}lobby-high.png`,timeout:90000});
  console.log('High quality performance',await page.evaluate(()=>({fps:__APEX__.fps,calls:__APEX__.rendering.renderer.info.render.calls,triangles:__APEX__.rendering.renderer.info.render.triangles})));
  await page.getByRole('button',{name:'ENTER COCKPIT'}).click();
  await page.waitForFunction(()=>__APEX__.phase==='drive');
  await page.screenshot({path:`${artifacts}cockpit-high.png`,timeout:90000});
  assert.deepEqual(errors,[],'No browser runtime or WebGL errors');
  console.log('Browser checks passed: startup, driving, braking, cameras, paused rendering/resize, telemetry, recover, settings, circuit, mobile, demonstration/takeover, lighting, high-quality pipeline.');
}finally{await browser.close()}
