import {browserOptions} from './browser-options.mjs';
import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch(browserOptions());
try{
 console.log('Browser launched');
 const page=await browser.newPage({viewport:{width:932,height:430},hasTouch:true});
 const errors=[];page.on('pageerror',e=>{errors.push(e.message);console.log('PAGE ERROR',e.message)});page.setDefaultTimeout(90000);
 await page.addInitScript(()=>localStorage.setItem('apex-settings',JSON.stringify({quality:'performance',volume:0})));
 await page.goto(process.env.APEX_URL||'http://127.0.0.1:4173');await page.waitForFunction(()=>window.__APEX__?.ready);console.log('Application ready');
 await page.getByRole('button',{name:'ENTER COCKPIT'}).click();
 await page.getByRole('button',{name:'Pause',exact:true}).click();
 await page.getByRole('button',{name:'EXIT TO PADDOCK'}).click();
 assert.equal(await page.locator('#countdown').isVisible(),false,'Leaving a paused countdown removes the overlay');console.log('Countdown exit passed');
 await page.getByRole('button',{name:'ENTER COCKPIT'}).click();await page.waitForFunction(()=>__APEX__.phase==='drive');console.log('Driving');
 const client=await page.context().newCDPSession(page);
 const pedal=await page.locator('[data-touch="throttle"]').boundingBox();assert(pedal);
 await client.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:pedal.x+pedal.width/2,y:pedal.y+pedal.height/2,id:1}]});
 console.log('Touch dispatched',await page.evaluate(()=>({touch:__APEX__.input.touch,phase:__APEX__.phase})));await page.waitForFunction(()=>__APEX__.state.speed>2);console.log('Touch acceleration passed');
 assert.equal(await page.evaluate(()=>__APEX__.input.touch.throttle),1);
 await page.keyboard.press('Escape');
 await page.waitForFunction(()=>__APEX__.phase==='paused');
 assert.equal(await page.evaluate(()=>__APEX__.input.touch.throttle),0,'Pause clears held touch pedal');
 await client.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
 await page.waitForTimeout(250);
 assert.equal(await page.evaluate(()=>__APEX__.phase),'paused','Releasing a held pedal must not resume the session');
 await page.getByRole('button',{name:'BACK ON TRACK'}).click();
 const camera=await page.evaluate(()=>__APEX__.cameras.mode);
 await page.getByRole('button',{name:'Change driving camera'}).click();
 assert.notEqual(await page.evaluate(()=>__APEX__.cameras.mode),camera);
 const boost=await page.getByRole('button',{name:'Hold for ERS boost'}).boundingBox();
 await client.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:boost.x+boost.width/2,y:boost.y+boost.height/2,id:2}]});
 assert.equal(await page.evaluate(()=>__APEX__.input.touch.boost),true);
 await client.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
 assert.equal(await page.evaluate(()=>__APEX__.input.touch.boost),false);console.log('Touch boost passed');
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:'DRIVER SETUP',exact:true}).click();
 await page.getByRole('switch',{name:'Automatic gearbox'}).click();
 await page.getByRole('button',{name:'SAVE & CONTINUE'}).click();
 const gear=await page.evaluate(()=>__APEX__.state.gear);
 const shift=await page.getByRole('button',{name:'Shift up',exact:true}).boundingBox();assert(shift);
 await client.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:shift.x+shift.width/2,y:shift.y+shift.height/2,id:3}]});
 await page.waitForFunction(previous=>__APEX__.state.gear===previous+1,gear);
 await page.waitForTimeout(250);
 assert.equal(await page.evaluate(()=>__APEX__.state.gear),gear+1,'Holding a shift button changes exactly one gear');
 await client.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
 assert.equal(await page.evaluate(()=>__APEX__.input.touch.gearUp),false);console.log('Touch manual shift passed');
 await page.evaluate(()=>{window.testPad={connected:true,id:'Regression controller',mapping:'standard',axes:[0,0],buttons:Array.from({length:17},()=>({pressed:false,value:0}))};Object.defineProperty(navigator,'getGamepads',{value:()=>[window.testPad],configurable:true});});
 await page.evaluate(()=>testPad.buttons[9].pressed=true);await page.waitForFunction(()=>__APEX__.phase==='paused');
 await page.evaluate(()=>testPad.buttons[9].pressed=false);await page.waitForTimeout(200);
 await page.evaluate(()=>testPad.buttons[9].pressed=true);await page.waitForFunction(()=>__APEX__.phase==='drive');
 const padCamera=await page.evaluate(()=>__APEX__.cameras.mode);
 await page.evaluate(()=>{testPad.buttons[9].pressed=false;testPad.buttons[8].pressed=true});
 await page.waitForFunction(previous=>__APEX__.cameras.mode!==previous,padCamera);
 await page.screenshot({path:'artifacts/touch-driving.png',timeout:90000});
 assert.deepEqual(errors,[]);
 console.log('Touch throttle/boost/camera, stuck-input clearing, countdown exit, and gamepad pause/resume/camera checks passed.');
}finally{await browser.close()}
